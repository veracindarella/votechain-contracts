#!/usr/bin/env bash
#
# Reproducible per-function gas report for the Soroban contracts.
#
# Runs the contract test suite with Soroban CPU/memory metering enabled and
# emits a deterministic markdown report for the key entry points:
#   create_proposal, cast_vote, finalise, execute
#
# Usage:
#   scripts/gas-report.sh            # writes gas-report.md
#   scripts/gas-report.sh out.md     # writes to a custom path
#
# The report is attached to release notes by the release workflow.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_FILE="${1:-${ROOT_DIR}/gas-report.md}"
CONTRACT_DIR="${ROOT_DIR}/contracts"

# Key functions covered by the report.
FUNCTIONS=(create_proposal cast_vote finalise execute)

if [[ ! -d "${CONTRACT_DIR}" ]]; then
  echo "error: contracts directory not found at ${CONTRACT_DIR}" >&2
  exit 1
fi

# Deterministic environment: fixed seed, no incremental artifacts, metering on.
export CARGO_INCREMENTAL=0
export RUST_BACKTRACE=1
export SOROBAN_GAS_REPORT=1

RAW_LOG="$(mktemp)"
trap 'rm -f "${RAW_LOG}"' EXIT

# Run the contract tests once; the harness prints per-function CPU/memory usage
# lines of the form:  gas: <fn> cpu=<n> mem=<n>
(
  cd "${CONTRACT_DIR}"
  cargo test --release -- --nocapture --test-threads=1
) 2>&1 | tee "${RAW_LOG}"

{
  echo "# Soroban Gas Report"
  echo
  echo "Generated by \`scripts/gas-report.sh\` (reproducible: \`cargo test --release\`, single-threaded)."
  echo
  echo "| Function | CPU instructions | Memory (bytes) |"
  echo "| --- | --- | --- |"
  for fn in "${FUNCTIONS[@]}"; do
    line="$(grep -E "gas: ${fn} " "${RAW_LOG}" | tail -n 1 || true)"
    if [[ -z "${line}" ]]; then
      echo "| \`${fn}\` | n/a | n/a |"
      continue
    fi
    cpu="$(sed -nE 's/.*cpu=([0-9]+).*/\1/p' <<<"${line}")"
    mem="$(sed -nE 's/.*mem=([0-9]+).*/\1/p' <<<"${line}")"
    echo "| \`${fn}\` | ${cpu:-n/a} | ${mem:-n/a} |"
  done
  echo
  echo "_Numbers are produced by the checked-in script and are stable across runs._"
} > "${OUT_FILE}"

echo "Gas report written to ${OUT_FILE}"